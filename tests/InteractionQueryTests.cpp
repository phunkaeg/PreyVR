int main()
{
    const auto baseline = preyvr::DecodeInteractionCandidates(kEdgeBaselineCandidates);
    const auto plus15 = preyvr::DecodeInteractionCandidates(kPlus15Candidates);
    const auto minus15 = preyvr::DecodeInteractionCandidates(kMinus15Candidates);
    Require(baseline.has_value() && plus15.has_value() && minus15.has_value(),
        "exact interaction candidate fixtures decode");
    Require(baseline->entityIds.size() == 2 &&
            baseline->entityIds[0] == 0xFDE0 && baseline->entityIds[1] == 0xFDE0,
        "edge baseline contains two keypad records");
    Require(plus15->entityIds.size() == 1 && plus15->entityIds[0] == 0xFDE0,
        "positive yaw removes one record but retains the keypad");
    Require(minus15->entityIds.size() == 1 && minus15->entityIds[0] == 0x1117,
        "negative yaw selects the captured adjacent entity");
    Require(preyvr::DidCommittedInteractionTargetChange(
            *baseline, 0xFDE0, *minus15, 0x1117),
        "candidate and committed usable entity change together");
    Require(!preyvr::DidCommittedInteractionTargetChange(
            *baseline, 0xFDE0, *plus15, 0xFDE0),
        "candidate-count-only change is not a target-change false positive");

    const auto truncated = std::span<const std::uint8_t>(
        kMinus15Candidates.data(), kMinus15Candidates.size() - 1);
    Require(!preyvr::DecodeInteractionCandidates(truncated).has_value(),
        "truncated candidate record fails closed");

    preyvr::CachedReticleState source{};
    source.origin = {780.9049f, 1569.4373f, 17.066854f};
    source.direction = {-0.22540966f, -0.9172588f, -0.32837006f};
    source.screenPosition = {0.5f, 0.575f};
    const auto probe = preyvr::MakeBoundedYawProbe(source, -15.0f);
    Require(probe.has_value(), "captured negative fifteen-degree probe is accepted");
    const auto encoded = preyvr::EncodeDirectionBytes(probe->direction);
    Require(encoded.has_value() && *encoded == kMinus15DirectionBytes,
        "captured interaction direction bytes reproduce exactly");

    preyvr::Vec3 scaled{
        probe->direction.x * 2.5f,
        probe->direction.y * 2.5f,
        probe->direction.z * 2.5f,
    };
    std::array<std::uint8_t, 12> scaledBytes{};
    std::memcpy(scaledBytes.data(), &scaled, sizeof(scaled));
    Require(scaledBytes == kMinus15ScaledBytes,
        "native 2.5-unit query vector reproduces exactly");

    std::cout << "PreyVR interaction-query fixture tests passed\n";
    return 0;
}
