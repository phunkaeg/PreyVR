int main()
{
    const auto component = preyvr::DecodeWrenchComponentState(kComponentFixture);
    Require(component.has_value(), "captured wrench component decodes");
    Require(Near(component->hitOffset, 1.0f), "captured hit offset is retained");
    Require(Near(component->rayRange, 2.75f), "captured melee range is retained");
    Require(Near(component->speedRangeMax, 2.0f), "captured speed range is retained");

    const auto hits = preyvr::DecodeRayHits(kRayHitFixture);
    Require(hits.has_value() && hits->size() == 4, "four captured wall hits decode");
    Require(Near((*hits)[0].distance, 0.531901f), "first hit distance is retained");
    Require(Near((*hits)[0].point.x, 768.089722f), "first hit point is retained");
    Require((*hits)[0].surfaceIndex == 153, "first hit surface is retained");

    const preyvr::RayHit* nearest = preyvr::NearestRayHit(*hits);
    Require(nearest == &(*hits)[0], "nearest hit policy selects the first wall contact");
    Require(!preyvr::DecodeRayHits(std::span(kRayHitFixture).first(319)).has_value(),
        "truncated hit fixture fails closed");

    const auto baselineA0b = preyvr::DecodeRayHits(kA0bBaselineHit);
    const auto syntheticA0b = preyvr::DecodeRayHits(kA0bSyntheticHit);
    Require(baselineA0b && baselineA0b->size() == 1,
        "A0b baseline contains one wall contact");
    Require(syntheticA0b && syntheticA0b->size() == 1,
        "A0b synthetic query contains one wall contact");

    const preyvr::RayHit& baselineHit = baselineA0b->front();
    const preyvr::RayHit& syntheticHit = syntheticA0b->front();
    Require(baselineHit.collider == syntheticHit.collider,
        "A0b yaw retains the same wall collider");
    Require(Near(baselineHit.distance, syntheticHit.distance, 0.001f),
        "A0b yaw retains wall depth");

    const float contactDeltaX = syntheticHit.point.x - baselineHit.point.x;
    const float contactDeltaY = syntheticHit.point.y - baselineHit.point.y;
    const float contactDeltaZ = syntheticHit.point.z - baselineHit.point.z;
    const float contactDelta = std::sqrt(
        contactDeltaX * contactDeltaX +
        contactDeltaY * contactDeltaY +
        contactDeltaZ * contactDeltaZ);
    Require(Near(contactDeltaX, 0.126160f, 0.0002f),
        "A0b contact moves laterally with positive yaw");
    Require(std::fabs(contactDeltaY) < 0.001f,
        "A0b contact remains on the same wall plane");
    Require(Near(contactDelta, 0.127165f, 0.0002f),
        "A0b contact displacement is retained");

    constexpr preyvr::Vec3 syntheticOrigin = {
        781.5918579101562f, 1569.457275390625f, 17.085979461669922f};
    constexpr preyvr::Vec3 syntheticDirection = {
        0.070487335f, -0.990096271f, -0.121411689f};
    Require(Near(
        syntheticOrigin.x + syntheticDirection.x * syntheticHit.distance,
        syntheticHit.point.x,
        0.0002f), "synthetic contact X follows the written ray");
    Require(Near(
        syntheticOrigin.y + syntheticDirection.y * syntheticHit.distance,
        syntheticHit.point.y,
        0.0002f), "synthetic contact Y follows the written ray");
    Require(Near(
        syntheticOrigin.z + syntheticDirection.z * syntheticHit.distance,
        syntheticHit.point.z,
        0.0002f), "synthetic contact Z follows the written ray");

    std::cout << "PreyVR wrench-query fixture tests passed\n";
    return 0;
}
