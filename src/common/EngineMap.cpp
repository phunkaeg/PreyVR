std::span<const Landmark> Landmarks()
{
    return kLandmarks;
}

LandmarkValidation ValidateLandmark(
    std::span<const std::uint8_t> mappedImage,
    const Landmark& landmark)
{
    if (landmark.rva > mappedImage.size() ||
        landmark.expected.size() > mappedImage.size() - landmark.rva) {
        return {&landmark, LandmarkStatus::outOfRange, 0};
    }

    const auto actual = mappedImage.subspan(landmark.rva, landmark.expected.size());
    const auto mismatch = std::mismatch(actual.begin(), actual.end(), landmark.expected.begin());
    if (mismatch.first != actual.end()) {
        return {
            &landmark,
            LandmarkStatus::mismatch,
            static_cast<std::size_t>(mismatch.first - actual.begin()),
        };
    }
    return {&landmark, LandmarkStatus::match, 0};
}

std::vector<LandmarkValidation> ValidateLandmarks(std::span<const std::uint8_t> mappedImage)
{
    std::vector<LandmarkValidation> results;
    results.reserve(kLandmarks.size());
    for (const Landmark& landmark : kLandmarks) {
        results.push_back(ValidateLandmark(mappedImage, landmark));
    }
    return results;
}

bool AllLandmarksMatch(std::span<const LandmarkValidation> results)
{
    return !results.empty() &&
        std::all_of(results.begin(), results.end(), [](const LandmarkValidation& result) {
        return result.status == LandmarkStatus::match;
    });
}

std::string_view ToString(LandmarkStatus status)
{
    switch (status) {
    case LandmarkStatus::match:
        return "match";
    case LandmarkStatus::outOfRange:
        return "out_of_range";
    case LandmarkStatus::mismatch:
        return "mismatch";
    }
    return "unknown";
}

